/**
 * Copies every destination's card photograph into `public/photos/cards/`, and
 * writes the list of what it copied to `src/lib/cachedCardPhotos.ts`.
 *
 *   npx tsx scripts/cache-card-photos.ts
 *
 * WHY. The cards used to load their photographs straight from Wikimedia and
 * Unsplash: 150–320KB JPEGs with no cache lifetime, a dozen of them on the
 * homepage. Routing them through Next's image optimiser instead does not work
 * either — Wikimedia rate-limits server-side fetchers (429), so a burst of
 * first visits would leave cards without photographs. A copy on our own origin
 * is fetched once, here, politely, and then served from the CDN for good.
 *
 * Each file is a 4:5 centre crop at 512×640 WebP: as tall as the rendition the
 * hall's card texture was drawn from before, and the shape of the homepage's
 * tiles. The manifest is untouched, so the credits page still names every one.
 *
 * Re-run it when the manifest changes; it skips files that already exist.
 */

import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import sharp from "sharp";

import { countriesData, getCountrySlug } from "../src/data/countries";
import { countryCardImage } from "../src/lib/countryImagery";
import { pickRendition } from "../src/components/country-stage/cardTexture";

const OUT_DIR = path.join(process.cwd(), "public/photos/cards");
const LIST = path.join(process.cwd(), "src/lib/cachedCardPhotos.ts");
// Wikimedia refuses requests without one: https://w.wiki/4wJS
const USER_AGENT = "abizon-photo-cache/1.0 (https://abizonvisa.com; one-off build script)";

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

async function fetchWithBackoff(url: string): Promise<Buffer> {
  for (let attempt = 0; attempt < 6; attempt++) {
    const res = await fetch(url, { headers: { "User-Agent": USER_AGENT } });
    if (res.ok) return Buffer.from(await res.arrayBuffer());
    if (res.status !== 429 && res.status < 500) throw new Error(`${res.status} ${url}`);
    const wait = Number(res.headers.get("retry-after")) * 1000 || 4000 * 2 ** attempt;
    console.log(`  ${res.status}, waiting ${Math.round(wait / 1000)}s`);
    await sleep(wait);
  }
  throw new Error(`gave up on ${url}`);
}

async function main() {
  mkdirSync(OUT_DIR, { recursive: true });
  const slugs = [...new Set(countriesData.map((c) => getCountrySlug(c.name)))];
  const cached: string[] = [];

  for (const slug of slugs) {
    const photo = countryCardImage(slug);
    if (!photo) continue;
    const file = path.join(OUT_DIR, `${slug}.webp`);
    if (existsSync(file)) {
      cached.push(slug);
      continue;
    }
    // A local photograph is already on our origin.
    if (photo.src.startsWith("/")) continue;

    const url = pickRendition(photo.src, photo.srcSet);
    try {
      const input = await fetchWithBackoff(url);
      await sharp(input)
        .resize(512, 640, { fit: "cover", position: "centre" })
        .webp({ quality: 74, effort: 6 })
        .toFile(file);
      cached.push(slug);
      console.log(`ok  ${slug}`);
    } catch (err) {
      console.warn(`--  ${slug}: ${(err as Error).message}`);
    }
    await sleep(1200);
  }

  cached.sort();
  writeFileSync(
    LIST,
    `/**
 * GENERATED by scripts/cache-card-photos.ts — do not edit by hand.
 *
 * Destinations whose card photograph has a copy at /photos/cards/<slug>.webp.
 * \`countryCardImage\` serves that copy instead of the remote original.
 */
export const CACHED_CARD_PHOTOS: ReadonlySet<string> = new Set(${JSON.stringify(cached, null, 2)});
`,
  );
  console.log(`\n${cached.length} cached; list written to ${path.relative(process.cwd(), LIST)}`);
}

main();
