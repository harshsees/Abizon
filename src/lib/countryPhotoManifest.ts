/**
 * THE GENERATED HALF OF THE COUNTRY IMAGE MANIFEST.
 *
 * One reviewed photograph per destination, 152 of them, sourced from Wikimedia
 * Commons by way of the English Wikipedia article for a named landmark in that
 * country. `lib/countryImagery.ts` is the module that consumes this and remains
 * the place where the rules live; this file is only the data.
 *
 * HOW EACH ROW WAS PRODUCED, and what that buys.
 *
 * The unit of trust in this manifest has always been a REVIEW — a named
 * subject, a verdict, and a date — rather than a URL, because Phase 8B found
 * seven photographs showing the wrong country entirely (Bangkok filed under
 * France, Mount Fuji under Nepal) behind a check that only ever asked whether a
 * URL resolved. That standard is unchanged. What changed is how the subject is
 * established: instead of someone opening a stock photo and guessing where it
 * was taken, each row starts from a landmark whose identity is not in question
 * — Wat Arun, the Matterhorn, Angkor Wat — and takes the lead photograph of
 * that landmark's own encyclopedia article. The subject line is therefore a
 * description of a known place, not an interpretation of an unknown frame.
 *
 * Every row was then filtered and probed by the sourcing script:
 *
 *   not a diagram   Wikipedia's "page image" for a geography article is very
 *                   often a locator map, a flag, a coat of arms or a city
 *                   collage. Victoria Harbour's was a 1957 British War Office
 *                   map; Cuba's was a street map of Habana Vieja. Those, and
 *                   satellite frames shot from the ISS, are rejected by name.
 *   large enough    below ~900px the file is a thumbnail of something better,
 *                   and the card alone asks for ~640px of width.
 *   actually there  every derived URL was requested before it was written here.
 *
 * WIDTHS ARE NOT FREE-FORM. Wikimedia rejects a hotlinked thumbnail at any
 * width outside its published standard set (20, 40, 60, 120, 250, 330, 500,
 * 960, 1280, 1920, 3840) and rejects upscales beyond the original. `widths` is
 * therefore the subset of that ladder which this particular file can actually
 * serve — it is data, not a preference, and inventing an entry produces a 400.
 *
 * LICENSING. These are free-licensed files, but "free" mostly means CC BY or
 * CC BY-SA, which require attribution. `credit`, `license` and `source` carry
 * what is needed to give it, and `CountryHero` renders a credit line over the
 * photograph. The cards on the homepage do not — 152 credits in a grid is not a
 * design — so the country page is where the obligation is discharged.
 *
 * ── DO NOT EDIT THIS FILE ────────────────────────────────────────────────
 *
 * It is generated by `scripts/country-photos/source.mjs`, from the landmark
 * list in `scripts/country-photos/landmarks.json`. To change a destination's
 * photograph, name a different landmark there and run:
 *
 *     node scripts/country-photos/source.mjs
 *
 * Editing a `ref` here by hand is how a 400 gets shipped: Wikimedia serves
 * thumbnails only at the widths in `widths`, and only up to the source file's
 * own size, so a URL that looks right and has not been probed usually is not.
 */

